#!/usr/bin/env node
/*
 * build-bar-notes.mjs - writes one sentence into the round-bar pages of the
 * grades in PAGES: the standard a bar is ordered to, and the flat-product
 * standard it must not be confused with.
 *
 *   "Round bar is specified to ASTM B446 / B564 / AMS 5666. Our sheet and plate
 *    pages cite ASTM B443 / AMS 5599 / 5869. Flat-product standards do not apply
 *    to bar, so name ASTM B446 on a bar order."
 *
 * WHY. The round-bar pages of a grade shared 44-49% of their text with the
 * next grade's, and the shared part was the hand-typed Specification Overview
 * table, which also carried the errors docs/specs.csv exists to stop: EN 10295
 * (a castings standard) on a bar page, a wire standard in a bar row. This
 * sentence is the one thing on the page only that grade can carry, it is
 * derived from the CSV rather than typed, and it names the mistake the CSV
 * warns about - a flat standard cited for a bar order - in terms a buyer can act on.
 *
 * It claims nothing the CSV does not hold: the bar and flat cells, as filled
 * from the mills' bulletins and the business's confirmed supply. A grade whose
 * bar or flat cell is '-', 'mill' or empty gets no sentence rather than a
 * vague one.
 *
 *   node docs/build-bar-notes.mjs          # write the sentences
 *   node docs/build-bar-notes.mjs --check  # report drift, write nothing
 *
 * Works in LF space and restores the CRLF it found; see CLAUDE.md.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

// page file -> the (family, grade) row of docs/specs.csv. Explicit, like the
// other generators' maps: the URL does not spell the CSV key (C276 is "C-276").
const PAGES = [
  ["inconel/600/round-bar.html", "inconel", "600"],
  ["inconel/601/round-bar.html", "inconel", "601"],
  ["inconel/625/round-bar.html", "inconel", "625"],
  ["inconel/718/round-bar.html", "inconel", "718"],
  ["hastelloy/C276/round-bar.html", "hastelloy", "C-276"],
  ["hastelloy/C22/round-bar.html", "hastelloy", "C-22"],
  ["titanium/grade-5/round-bar.html", "titanium", "Grade 5"],
  ["titanium/Grade-2/round-bar.html", "titanium", "Grade 2"],
  ["monel/400/round-bar.html", "monel", "400"],
  ["monel/K-500/round-bar.html", "monel", "K-500"],
  ["incoloy/825/round-bar.html", "incoloy", "825"],
];

const START = "<!-- bar-note:start  generated by docs/build-bar-notes.mjs -->";
const END = "<!-- bar-note:end -->";
const ANCHOR = "<!-- calc-cta:start";

// docs/specs.csv: '#' comment lines, then a header, then one row per grade.
const rows = readFileSync(join(ROOT, "docs/specs.csv"), "utf8")
  .replace(/\r\n/g, "\n").split("\n").filter((l) => l && !l.startsWith("#"));
const header = rows.shift().split(",");
const specs = new Map();
for (const line of rows) {
  const c = line.split(",");
  specs.set(`${c[0]}|${c[1]}`, Object.fromEntries(header.map((h, i) => [h, (c[i] || "").trim()])));
}

const usable = (v) => v && v !== "-" && v !== "mill";
let drift = 0, written = 0;
const skipped = [];

for (const [file, family, grade] of PAGES) {
  const row = specs.get(`${family}|${grade}`);
  if (!row) { skipped.push(`${file}: no specs.csv row for ${family} ${grade}`); continue; }
  if (!usable(row.bar) || !usable(row.flat)) {
    skipped.push(`${file}: bar or flat cell is '${row.bar}' / '${row.flat}', no sentence written`);
    continue;
  }

  const primary = row.bar.split(" / ")[0];
  const text =
    `Round bar is specified to ${row.bar}. Our sheet and plate pages cite ${row.flat}. ` +
    `Flat-product standards do not apply to bar, so name ${primary} on a bar order.`;
  const block = `        ${START}\n        <p class="bar-standard-note">${text}</p>\n        ${END}\n`;

  let raw;
  try { raw = readFileSync(join(ROOT, file), "utf8"); }
  catch { skipped.push(`${file}: file not found`); continue; }
  const crlf = raw.includes("\r\n");
  let s = raw.replace(/\r\n/g, "\n");

  s = s.replace(/[ \t]*<!-- bar-note:start[\s\S]*?<!-- bar-note:end -->\n?/g, "");
  const at = s.indexOf(ANCHOR);
  if (at < 0) { skipped.push(`${file}: no calc-cta block to anchor on`); continue; }
  const lineStart = s.lastIndexOf("\n", at) + 1;
  s = s.slice(0, lineStart) + block + s.slice(lineStart);

  if (s !== raw.replace(/\r\n/g, "\n")) {
    drift++;
    if (!CHECK) {
      writeFileSync(join(ROOT, file), crlf ? s.replace(/\n/g, "\r\n") : s);
      written++;
    }
  }
}

for (const n of skipped) console.log("skipped:", n);
if (CHECK) {
  if (drift) { console.log(`${drift} page(s) out of date. Run: node docs/build-bar-notes.mjs`); process.exit(1); }
  console.log("All bar-standard notes up to date.");
} else {
  console.log(`${written} page(s) written (${PAGES.length - skipped.length} with a sentence).`);
}

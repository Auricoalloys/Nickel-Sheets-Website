#!/usr/bin/env node
/*
 * build-form-links.mjs - writes an "Other forms of <grade>" block into the form
 * pages of the grades listed in GRADES, linking each page to its siblings and
 * to the grade hub.
 *
 * WHY. Search Console (2026-10-13) showed /inconel/718/sheets/ as "Discovered -
 * currently not indexed" with no crawl at all: Google knew it from sitemap.xml
 * and one catalogue page and had never fetched it. The plates pages had three
 * inbound links each, sheets 11-17, while round bars had ~90 from their shared
 * sidebar. A page nothing crawled links to is a page Google does not spend
 * a fetch on, so the siblings - which ARE crawled - are given a way across.
 *
 * It is a generator, not hand edits, for the reason every block here is: a
 * form page added next year must appear in its siblings' lists without anyone
 * remembering to, and a retired one must leave them. Labels are each sibling's
 * own last BreadcrumbList crumb, which this repo already treats as the clean
 * hand-written name (see CLAUDE.md, the enquiry subject).
 *
 *   node docs/build-form-links.mjs          # write the blocks
 *   node docs/build-form-links.mjs --check  # report drift, write nothing
 *
 * Scope is the GRADES list, deliberately: adding a grade is one line, and the
 * first run touches only the pages whose ranking is being worked on. Powder is
 * never listed as a sibling - it is a different production route.
 *
 * Does its work in LF space and restores the CRLF it found; see CLAUDE.md.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

// family/grade as it appears in the URL, lower-cased.
const GRADES = [
  "inconel/600", "inconel/601", "inconel/625", "inconel/718",
  "hastelloy/c276", "hastelloy/c22",
  "titanium/grade-2", "titanium/grade-5",
];

// A form page that lives at a flat permalink rather than /family/grade/form/.
const FLAT = {
  "/titanium/grade-5-plates/": { grade: "titanium/grade-5", form: "plates" },
};

// Order the siblings print in, and the only forms that count as one.
const FORMS = ["sheets", "plates", "coil", "round-bar", "foil", "wire", "pipe", "tube", "fittings"];

const START = "<!-- form-links:start  generated by docs/build-form-links.mjs -->";
const END = "<!-- form-links:end -->";
const ANCHOR = "<!-- calc-cta:end -->";

const files = execSync('git ls-files "*.html"', { encoding: "utf8", maxBuffer: 1 << 28 })
  .trim().split("\n");

const pages = [];
for (const f of files) {
  let raw;
  try { raw = readFileSync(join(ROOT, f), "utf8"); } catch { continue; }
  const s = raw.replace(/\r\n/g, "\n");
  if (!s.startsWith("---")) continue;
  const end = s.indexOf("\n---", 3);
  if (end < 0) continue;
  const fm = s.slice(0, end);
  const pm = fm.match(/^permalink:[ \t]*(\S+)/m);
  if (!pm) continue;
  if (/^published:[ \t]*false/m.test(fm) || /^sitemap:[ \t]*false/m.test(fm)) continue;
  pages.push({ f, raw, s, url: pm[1].replace(/["']/g, "") });
}

/** Last BreadcrumbList crumb, or '' when the page has none that parses. */
function lastCrumb(s) {
  const body = s.replace(/<!--[\s\S]*?-->/g, "");
  const re = /<script[^>]*ld\+json[^>]*>([\s\S]*?)<\/script>/gi;
  let m;
  while ((m = re.exec(body))) {
    let j;
    try { j = JSON.parse(m[1]); } catch { continue; }
    for (const node of Array.isArray(j) ? j : [j]) {
      const list = node && node["@type"] === "BreadcrumbList" ? node.itemListElement : null;
      if (list && list.length) {
        const sorted = [...list].sort((a, b) => a.position - b.position);
        return String(sorted[sorted.length - 1].name || "").trim();
      }
    }
  }
  return "";
}

const esc = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function describe(p) {
  if (FLAT[p.url]) return { ...FLAT[p.url], page: p };
  const m = p.url.match(/^\/([^/]+)\/([^/]+)\/([^/]+)\/$/);
  if (!m) return null;
  const form = m[3].toLowerCase();
  const normForm = form === "plate" ? "plates" : form === "sheet" ? "sheets" : form;
  if (!FORMS.includes(normForm)) return null;
  return { grade: `${m[1]}/${m[2]}`.toLowerCase(), form: normForm, page: p };
}

const byGrade = new Map();
for (const p of pages) {
  const d = describe(p);
  if (!d || !GRADES.includes(d.grade)) continue;
  if (!byGrade.has(d.grade)) byGrade.set(d.grade, []);
  byGrade.get(d.grade).push(d);
}

const hubOf = (grade) => pages.find((p) => p.url.toLowerCase() === `/${grade}/`);

let drift = 0, written = 0, skipped = [];

for (const [grade, members] of byGrade) {
  members.sort((a, b) => FORMS.indexOf(a.form) - FORMS.indexOf(b.form));

  const labelled = [];
  for (const d of members) {
    const label = lastCrumb(d.page.s);
    if (!label) { skipped.push(`${d.page.url}: no BreadcrumbList label, left out of its siblings' lists`); continue; }
    labelled.push({ ...d, label });
  }

  const hub = hubOf(grade);
  const hubLabel = hub ? lastCrumb(hub.s) : "";
  // A hub whose own crumb names a form is the form-page-at-a-grade-URL defect
  // (CLAUDE.md); naming it in this block would repeat it.
  const hubOk = hub && hubLabel && !FORMS.some((w) => new RegExp(`\\b${w.replace("-", "[- ]")}\\b`, "i").test(hubLabel));
  if (hub && !hubOk) skipped.push(`${hub.url}: hub label "${hubLabel}" is empty or names a form, hub link left out`);

  for (const d of labelled) {
    const p = d.page;
    const sibs = labelled.filter((x) => x !== d);
    if (!sibs.length && !hubOk) continue;

    const items = sibs.map((x) => `            <li><a href="${x.page.url}">${esc(x.label)}</a></li>`).join("\n");
    const hubLine = hubOk
      ? `          <p class="form-links-hub"><a href="${hub.url}">${esc(hubLabel)} &ndash; specifications and every form &rarr;</a></p>\n`
      : "";
    const block =
      `        ${START}\n` +
      `        <aside class="form-links" aria-label="Other forms of ${esc(hubOk ? hubLabel : grade)}">\n` +
      (sibs.length
        ? `          <p class="form-links-title"><strong>Also supplied as</strong></p>\n          <ul class="form-links-list">\n${items}\n          </ul>\n`
        : "") +
      hubLine +
      `        </aside>\n` +
      `        ${END}`;

    let s = p.s;
    // Drop what a previous run wrote, then place it again after the anchor.
    s = s.replace(/[ \t]*<!-- form-links:start[\s\S]*?<!-- form-links:end -->\n?/g, "");
    const at = s.indexOf(ANCHOR);
    if (at < 0) { skipped.push(`${p.url}: no calc-cta block to anchor on`); continue; }
    const lineEnd = s.indexOf("\n", at);
    s = s.slice(0, lineEnd + 1) + block + "\n" + s.slice(lineEnd + 1);

    if (s !== p.s) {
      drift++;
      if (!CHECK) {
        const crlf = p.raw.includes("\r\n");
        writeFileSync(join(ROOT, p.f), crlf ? s.replace(/\n/g, "\r\n") : s);
        written++;
      }
    }
  }
}

for (const note of skipped) console.log("skipped:", note);
const pagesSeen = [...byGrade.values()].reduce((n, a) => n + a.length, 0);
console.log(`${pagesSeen} form pages across ${byGrade.size} grades.`);

if (CHECK) {
  if (drift) { console.log(`${drift} page(s) out of date. Run: node docs/build-form-links.mjs`); process.exit(1); }
  console.log("All form-link blocks up to date.");
} else {
  console.log(`${written} page(s) written.`);
}

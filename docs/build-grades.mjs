// Writes the Equivalent Grades and Chemical Composition tables onto every
// product page from docs/grades.csv and docs/chemistry.csv, and lints every
// page for an identifier that contradicts the grade the page is about.
//
//   node docs/build-grades.mjs            write the tables into the pages
//   node docs/build-grades.mjs --check    report drift, write nothing, exit 1
//   node docs/build-grades.mjs --lint     only the contradiction report
//   node docs/build-grades.mjs --check --strict   also fail on contradictions
//
// Run it after editing docs/grades.csv or docs/chemistry.csv and commit the
// result, exactly like docs/build-specs.mjs. This script is excluded from the
// published site in _config.yml; the pages it edits are not.
//
// WHY THIS EXISTS: an audit of all 778 published pages on 2026-08-22 found the
// same figure typed onto a form page, a form hub and a grade hub, drifting
// apart exactly as the prices and the specs did before their CSVs existed - 4
// grades publishing conflicting UNS numbers, 24 conflicting Werkstoff numbers,
// 51 grades whose siblings disagreed on chemistry and 61 density/melting
// disagreements. incoloy/800/round-bar cited 2.4952, which is Nimonic 80A's
// number; monel/K-500/sheets carried Monel 400's density.
//
// TWO HALVES, and the lint is the half that pays off first:
//
//   The WRITER only touches a grade whose row in grades.csv carries a `checked`
//   date. Everything else keeps its hand-written tables. That is what makes the
//   migration safe - seeding the CSV changes no page until a human has verified
//   the row against a mill bulletin, so the file can be filled in one sitting
//   and adopted family by family.
//
//   The LINT runs on every page regardless of verification state, because
//   reporting a wrong UNS does not require the replacement to be ready.
//
// The tables are written between HTML marker comments, so re-running replaces
// only the generated block and never touches hand-written copy around it.

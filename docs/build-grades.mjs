function reportFindings() {
  if (!findings.length) { console.log('no contradicting identifiers found'); return; }
  console.log(`\ncontradicting identifiers in the identity zone: ${findings.length}`);
  console.log('(title / meta description / og / twitter / JSON-LD name)\n');
  const byFile = new Map();
  for (const f of findings) {
    if (!byFile.has(f.rel)) byFile.set(f.rel, []);
    byFile.get(f.rel).push(f);
  }
  for (const [rel, list] of byFile) {
    console.log(`  ${rel}`);
    for (const f of list) console.log(`      ${f.kind} ${f.found} on a ${f.grade} page - grades.csv says ${f.expected}`);
  }
}

if (LINT_ONLY) {
  if (dataErrors.length) {
    console.error(`data errors in the CSVs: ${dataErrors.length}`);
    dataErrors.forEach(e => console.error('   ' + e));
  }
  console.log(`pages scanned: ${scanned}   mapped to a grade: ${mapped}`);
  reportFindings();
  process.exit(findings.length && STRICT ? 1 : 0);
}

if (CHECK) {
  let bad = false;
  if (dataErrors.length) {
    console.error(`the CSVs disagree about what a grade is (${dataErrors.length}):`);
    dataErrors.forEach(e => console.error('   ' + e));
    bad = true;
  }
  if (drift.length) {
    console.error(`grade tables are STALE in ${drift.length} page(s) - run: node docs/build-grades.mjs`);
    drift.slice(0, 10).forEach(d => console.error('   ' + d));
    bad = true;
  }
  const cur = fs.existsSync(JSON_OUT) ? fs.readFileSync(JSON_OUT, 'utf8') : '';
  if (cur !== jsonPayload()) {
    console.error('docs/grades.json is stale - run: node docs/build-grades.mjs');
    bad = true;
  }
  reportFindings();
  if (findings.length && STRICT) bad = true;
  if (bad) process.exit(1);
  if (dataNotes.length) console.log(`  ${dataNotes.length} grade(s) with no specs.csv row - run with no flags to list them`);
  console.log(`grade tables are current (${grades.length} grades, ${nVerified} verified, ${chem.length} chemistry rows)`);
  process.exit(0);
}


// ---- integrity checks on the data itself ------------------------------------
// These are fatal in --check because they mean two files disagree about what a
// grade *is*, which is the exact failure this pipeline exists to prevent.
const dataErrors = [];
const dataNotes = [];

// A grade can carry more than one UNS where the mills publish more than one:
// duplex 2205 is S32205 and S31803, the modern higher-nitrogen version and the
// original. Write them "S32205 / S31803", most current first.
const unsList = v => String(v || '').split('/').map(x => x.trim().toUpperCase()).filter(x => x && x !== '-');

for (const s of specs) {
  const g = byKey.get(key(s.family, s.grade));
  if (!g) { dataErrors.push(`specs.csv has ${s.family}/${s.grade} but grades.csv does not`); continue; }
  const want = unsList(s.uns), have = unsList(g.uns);
  if (!want.length && !have.length) continue;
  if (!want.every(u => have.includes(u)))
    dataErrors.push(`UNS disagrees for ${s.family}/${s.grade}: specs.csv "${s.uns}" vs grades.csv "${g.uns}"`);
}
// grades.csv is the master list of materials and may lead specs.csv - the site
// sells Hastelloy B-3 before anyone has filled in its per-form standards. That
// is a gap to note, not a contradiction to fail on.
for (const g of grades) {
  if (!specs.find(s => s.family === g.family && s.grade === g.grade))
    dataNotes.push(`${g.family}/${g.grade} has no row in specs.csv - no per-form standards will be printed for it`);
}
// Rows that share a UNS are the same material listed under two family keys
// (nickel-alloy/Inconel 600 and inconel/600). They must not drift apart.
const byUns = new Map();
for (const g of grades) {
  for (const u of unsList(g.uns)) {
    if (!byUns.has(u)) byUns.set(u, []);
    byUns.get(u).push(g);
  }
}
for (const [uns, list] of byUns) {
  if (list.length < 2) continue;
  for (const f of ['wnr', 'en_name', 'density_g_cm3']) {
    const vals = [...new Set(list.map(r => r[f]).filter(Boolean))];
    if (vals.length > 1)
      dataErrors.push(`${uns} appears as ${list.map(r => r.family + '/' + r.grade).join(' and ')} with different ${f}: ${vals.join(' vs ')}`);
  }
}
for (const g of grades) {
  if (g.density_g_cm3 && !/^\d+(\.\d+)?$/.test(g.density_g_cm3))
    dataErrors.push(`${g.family}/${g.grade} density must be a bare number in g/cm3, got "${g.density_g_cm3}"`);
}
for (const c of chem) {
  if (!byKey.has(key(c.family, c.grade)))
    dataErrors.push(`chemistry.csv has ${c.family}/${c.grade} but grades.csv does not`);
  for (const f of ['min', 'max']) {
    const v = c[f];
    if (v && v !== 'bal' && !/^\d+(\.\d+)?$/.test(v))
      dataErrors.push(`${c.family}/${c.grade} ${c.element} ${f} must be a number, "bal" or empty, got "${v}"`);
  }
}

const verified = r => !!(r.checked && r.source && r.source !== 'pending');

// ---- table builders ---------------------------------------------------------
const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const dash = v => (!v || v === '-') ? '&mdash;' : esc(v);

const DISPLAY = {
  inconel: 'Inconel', incoloy: 'Incoloy', hastelloy: 'Hastelloy', monel: 'Monel',
  nimonic: 'Nimonic', haynes: 'Haynes', titanium: 'Titanium', nichrome: 'Nichrome',
  'duplex-steel': 'Duplex', 'cobalt-alloy': '', 'nickel-alloy': '',
  'special-stainless-steel': '', 'tool-steel': '',
};
const fullName = r => {
  const p = DISPLAY[r.family] ?? '';
  return p && !r.grade.toLowerCase().startsWith(p.toLowerCase()) ? `${p} ${r.grade}` : r.grade;
};

function identityTable(r, form) {
  // An empty cell means "not verified yet" and an explicit "-" means "the mill
  // publishes no such designation". Those are different claims, so an empty
  // cell drops its row rather than printing a dash the caption would then
  // describe as a mill statement.
  const rows = [
    ['UNS number', r.uns, v => dash(v)],
    ['Werkstoff / EN number', r.wnr, v => dash(v)],
    ['EN designation', r.en_name, v => dash(v)],
    ['Density', r.density_g_cm3, v => `${esc(v)} g/cm<sup>3</sup>`],
    ['Melting range', r.melting_c, v => `${esc(v)} &deg;C`],
  ].filter(([, v]) => v !== '' && v != null).map(([k, v, f]) => [k, f(v)]);

  // The standard for the form this page actually sells, never for another one.
  if (form) {
    const s = specs.find(x => x.family === r.family && x.grade === r.grade);
    const std = s && s[form];
    if (std && std !== '-') {
      rows.push([`${FORM_LABEL[form]} specification`,
        std === 'mill' ? 'Mill specification' : esc(std)]);
    }
  }
  return [
    '<div class="table-responsive">',
    '<table class="table table-bordered grade-table">',
    `<caption class="visually-hidden">Equivalent designations and physical constants for ${esc(fullName(r))}</caption>`,
    '<thead><tr><th scope="col">Designation</th><th scope="col">Value</th></tr></thead>',
    '<tbody>',
    ...rows.map(([k, v]) => `<tr><th scope="row">${esc(k)}</th><td>${v}</td></tr>`),
    '</tbody>',
    '</table>',
    '</div>',
    `<p class="small text-muted">Identifiers and physical constants for ${esc(fullName(r))} as published by the mill (${esc(r.source)}, checked ${esc(r.checked)}). A dash means the mill publishes no such designation for this grade.</p>`,
  ].join('\n');
}

function chemTable(r, rows) {
  const cell = (min, max) => {
    const lo = min ? esc(min) : '&mdash;';
    const hi = max === 'bal' ? 'Balance' : (max ? esc(max) : '&mdash;');
    return [lo, hi];
  };
  return [
    '<div class="table-responsive">',
    '<table class="table table-bordered">',
    `<caption class="visually-hidden">Chemical composition limits for ${esc(fullName(r))}</caption>`,
    '<thead><tr><th scope="col">Element</th><th scope="col">Min (%)</th><th scope="col">Max (%)</th></tr></thead>',
    '<tbody>',
    ...rows.map(c => {
      const [lo, hi] = cell(c.min, c.max);
      const nm = ELEMENT_NAMES[c.element];
      // The bulletin's own qualifier, e.g. "if determined" against cobalt in
      // the INCONEL 625 sheet. Printed rather than dropped, so the page can be
      // compared line for line against the mill's table.
      const note = c.note ? ` <span class="small text-muted">(${esc(c.note)})</span>` : '';
      return `<tr><th scope="row">${nm ? `${esc(nm)} (${esc(c.element)})` : esc(c.element)}</th><td>${lo}</td><td>${hi}${note}</td></tr>`;
    }),
    '</tbody>',
    '</table>',
    '</div>',
    `<p class="small text-muted">Composition limits per ${esc(r.source)}, checked ${esc(r.checked)}. These are specification limits for the grade, not measured values for a lot; the mill test certificate supplied with your order states the actual analysis.</p>`,
  ].join('\n');
}

// ---- page walking -----------------------------------------------------------
const SKIP = new Set(['.git', '.vscode', '.claude', 'node_modules', '_site', 'vendor', 'tools', '.bundle', '.github', 'docs', 'supabase']);
function walk(d, out = []) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const fp = path.join(d, e.name);
    if (e.isDirectory()) walk(fp, out);
    else if (/\.html?$/i.test(e.name)) out.push(fp);
  }
  return out;
}

const norm = s => String(s ?? '').toLowerCase().replace(/\([^)]*\)/g, '').replace(/[^a-z0-9]/g, '');
const familyOf = url => (FAMILY_KEYS.find(([k]) => url.toLowerCase().includes('/' + k + '/')) || [])[1] || null;

// Resolve /family/grade/[form/] to a CSV row. The grade segment is normalised
// so "625-LCF" finds "625 LCF" and "Grade-2" finds "Grade 2".
function gradeForUrl(url) {
  const family = familyOf(url);
  if (!family) return null;
  const segs = url.split('/').filter(Boolean);
  if (segs.length < 2) return null;
  const cand = norm(segs[1]);
  if (!cand) return null;
  const pool = grades.filter(r => r.family === family);
  // Longest grade name first so "625 LCF" wins over "625".
  const sorted = [...pool].sort((a, b) => norm(b.grade).length - norm(a.grade).length);
  return sorted.find(r => norm(r.grade) === cand)
    || sorted.find(r => norm(r.grade).replace(/^(inconel|incoloy|monel|nickel|hastelloy|haynes)/, '') === cand)
    || null;
}

// ---- the lint ---------------------------------------------------------------
// Only the identity zone is checked: title, meta description, og/twitter
// title+description and the JSON-LD name. A UNS in the body is usually a
// legitimate mention of a sibling grade in a cross-link list, and flagging
// those would bury the real findings.
const UNS_RE = /\b([NRSKJWCAGE]\d{5})\b/g;
const WNR_RE = /\b([123]\.\d{4})\b/g;

function identityZone(raw) {
  const head = (raw.match(/<head[\s\S]*?<\/head>/i) || [''])[0];
  const bits = [];
  const t = head.match(/<title>([\s\S]*?)<\/title>/i);
  if (t) bits.push(t[1]);
  for (const m of head.matchAll(/<meta\s+(?:name|property)="(?:description|og:title|og:description|twitter:title|twitter:description)"[^>]*content="([^"]*)"/gi))
    bits.push(m[1]);
  for (const m of raw.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/gi)) {
    for (const n of m[1].matchAll(/"(?:name|description)"\s*:\s*"((?:[^"\\]|\\.)*)"/g)) bits.push(n[1]);
  }
  return bits.join('\n');
}

// How many distinct grades of this family does the zone name? A foil page that
// legitimately covers 660, 686, 690, 693 and 718 must not be judged against
// one of them.
function gradesNamedIn(zone, family) {
  const z = zone.toLowerCase();
  const hits = new Set();
  for (const r of grades.filter(x => x.family === family)) {
    const g = r.grade.replace(/\([^)]*\)/g, '').trim();
    if (!g || g === '-') continue;
    const pat = g.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/[\s-]+/g, '[\\s\\u00ae.-]*');
    if (new RegExp(`(?:^|[^a-z0-9])${pat}(?![a-z0-9])`, 'i').test(z)) hits.add(r.grade);
  }
  // "625 LCF" also matches "625"; keep only the most specific.
  for (const a of [...hits]) for (const b of [...hits]) if (a !== b && norm(b).startsWith(norm(a))) hits.delete(a);
  return hits;
}

const findings = [];
let scanned = 0, mapped = 0;

// ---- apply ------------------------------------------------------------------
let wrote = 0;
const drift = [], noSection = [], unverifiedPages = new Map(), noChem = new Set();

for (const fp of walk(ROOT)) {
  const rel = path.relative(ROOT, fp).split(path.sep).join('/');
  const raw = fs.readFileSync(fp, 'utf8');
  const fm = raw.match(/^\ufeff?---\s*\r?\n([\s\S]*?)\r?\n---/);
  if (!fm || /^published:\s*false/m.test(fm[1])) continue;
  let url = ((fm[1].match(/^permalink:\s*(.+)$/m) || [, ''])[1] || '').trim().replace(/^["']|["']$/g, '');
  if (!url) continue;
  if (!url.startsWith('/')) url = '/' + url;
  if (!url.endsWith('/')) url += '/';
  scanned++;

  const row = gradeForUrl(url);
  if (!row) continue;
  mapped++;

  // --- lint (runs whether or not the row is verified) ---
  const zone = identityZone(raw);
  const named = gradesNamedIn(zone, row.family);
  const single = named.size <= 1;
  if (single) {
    const seenU = new Set([...zone.matchAll(UNS_RE)].map(m => m[1].toUpperCase()));
    const seenW = new Set([...zone.matchAll(WNR_RE)].map(m => m[1]));
    const wantU = unsList(row.uns);
    const wantW = row.wnr || '';
    for (const u of seenU) {
      if (wantU.length && !wantU.includes(u))
        findings.push({ rel, kind: 'UNS', found: u, expected: row.uns, grade: fullName(row) });
      else if (!wantU.length)
        findings.push({ rel, kind: 'UNS', found: u, expected: '(none published)', grade: fullName(row) });
    }
    for (const w of seenW) {
      if (wantW && wantW !== '-' && w !== wantW)
        findings.push({ rel, kind: 'W.Nr', found: w, expected: row.wnr, grade: fullName(row) });
    }
  }

  // --- writer (verified rows only) ---
  if (!verified(row)) {
    const k = `${row.family}/${row.grade}`;
    unverifiedPages.set(k, (unverifiedPages.get(k) || 0) + 1);
    continue;
  }

  const crlf = raw.includes('\r\n');
  let s = raw.replace(/\r\n/g, '\n');
  const before = s;

  const formSeg = url.split('/').filter(Boolean)[2];
  const form = formSeg ? (FORM_OF_SEGMENT[formSeg.toLowerCase()] || null) : null;

  const blocks = [
    { section: ID_SECTION, start: ID_START, end: ID_END, html: identityTable(row, form) },
  ];
  const cr = chemOf.get(key(row.family, row.grade));
  if (cr && cr.length) {
    blocks.push({ section: CHEM_SECTION, start: CHEM_START, end: CHEM_END, html: chemTable(row, cr) });
  } else {
    noChem.add(`${row.family}/${row.grade}`);
  }

  for (const b of blocks) {
    const block = `${b.start}\n${b.html}\n${b.end}`;
    const re = new RegExp(b.start.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + b.end.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
    if (re.test(s)) { s = s.replace(re, block); continue; }

    // First run: swap the hand-written table inside the known section. A page
    // with the section but no table is reported, never guessed at - same rule
    // as build-prices.mjs and build-specs.mjs.
    const at = s.indexOf(b.section);
    if (at < 0) continue;
    const secEnd = s.indexOf('</section>', at);
    if (secEnd < 0) { noSection.push(`${rel}  (unterminated ${b.section.match(/id="([^"]+)"/)[1]})`); continue; }
    const chunk = s.slice(at, secEnd);
    const tStart = chunk.indexOf('<table');
    const tEnd = chunk.indexOf('</table>');
    if (tStart < 0 || tEnd < 0) { noSection.push(`${rel}  (no table in ${b.section.match(/id="([^"]+)"/)[1]})`); continue; }
    // Widen to the wrapping .table-responsive div when there is one.
    let from = at + tStart, to = at + tEnd + '</table>'.length;
    const wrapAt = chunk.lastIndexOf('<div class="table-responsive">', tStart);
    if (wrapAt > -1) {
      const closeAt = chunk.indexOf('</div>', tEnd);
      if (closeAt > -1) { from = at + wrapAt; to = at + closeAt + '</div>'.length; }
    }
    s = s.slice(0, from) + block + s.slice(to);
  }

  if (s !== before) {
    if (CHECK) drift.push(rel);
    else { fs.writeFileSync(fp, crlf ? s.replace(/\n/g, '\r\n') : s); wrote++; }
  }
}


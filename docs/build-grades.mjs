function identityTable(r, form) {
  // An empty cell means "not verified yet" and an explicit "-" means "the mill
  // publishes no such designation". Those are different claims, so an empty
  // cell drops its row rather than printing a dash the caption would then
  // describe as a mill statement.
  const rows = [
    ['UNS number', r.uns, v => dash(v)],
    ['Werkstoff / EN number', r.wnr, v => dash(v)],
    ['EN designation', r.en_name, v => dash(v)],
    ['Density', r.density_g_cm3, v => `${esc(v)} g/cm<sup>3</sup>`],
    ['Melting range', r.melting_c, v => `${esc(v)} &deg;C`],
  ].filter(([, v]) => v !== '' && v != null).map(([k, v, f]) => [k, f(v)]);

  // The rest of the mill's physical constants, in the order the bulletin prints
  // them. The unit travels with the value rather than being implied by the row
  // label, because the bulletins do not publish every constant in SI - X-750's
  // Curie temperature is given in °F only - and converting one here would put a
  // figure on the page that the mill never printed.
  for (const p of propsOf.get(key(r.family, r.grade)) || []) {
    if (!p.value) continue;
    const label = p.condition ? `${p.property} (${p.condition})` : p.property;
    const value = p.unit ? `${esc(p.value)} ${esc(p.unit)}` : esc(p.value);
    const note = p.note ? ` <span class="small text-muted">(${esc(p.note)})</span>` : '';
    rows.push([label, value + note]);
  }

  // The standard for the form this page actually sells, never for another one.
  if (form) {
    const s = specs.find(x => x.family === r.family && x.grade === r.grade);
    const std = s && s[form];
    if (std && std !== '-') {
      rows.push([`${FORM_LABEL[form]} specification`,
        std === 'mill' ? 'Mill specification' : esc(std)]);
    }
  }
  return [
    '<div class="table-responsive">',
    '<table class="table table-bordered grade-table">',
    `<caption class="visually-hidden">Equivalent designations and physical constants for ${esc(fullName(r))}</caption>`,
    // "Property", not "Designation": the table has always mixed identifiers with
    // physical constants, and now carries a dozen more of the latter.
    '<thead><tr><th scope="col">Property</th><th scope="col">Value</th></tr></thead>',
    '<tbody>',
    ...rows.map(([k, v]) => `<tr><th scope="row">${esc(k)}</th><td>${v}</td></tr>`),
    '</tbody>',
    '</table>',
    '</div>',
    // "the source cited", not "the mill": most rows come from a mill bulletin,
    // but Hastelloy B-2 is sourced to ASTM B333 because no mill publishes the
    // grade any more, and a caption claiming a mill published it would be false.
    `<p class="small text-muted">Identifiers and physical constants for ${esc(fullName(r))} as published in the source cited (${esc(r.source)}, checked ${esc(r.checked)}). A dash means that source publishes no such designation for this grade.</p>`,
  ].join('\n');
}

function chemTable(r, rows) {
  const cell = (min, max) => {
    const lo = min ? esc(min) : '&mdash;';
    const hi = max === 'bal' ? 'Balance' : (max ? esc(max) : '&mdash;');
    return [lo, hi];
  };
  // How the caption may describe the table depends on what is in it. A row with
  // no min and no max is a nominal figure, and calling it a limit in the caption
  // is the exact claim the nominal handling below exists to avoid making - the
  // NIMONIC 86 table is nominal end to end, so "Chemical composition limits for
  // Nimonic 86" over five cells each reading "nominal" had the page contradict
  // itself in the one place a screen reader hears first.
  //
  // "Balance" counts as neither. It is what is left after everything else and
  // is never an acceptance limit, so a table of nominal figures plus a balance
  // row - which is exactly the shape of the NIMONIC 86 and 901 tables - is
  // still a nominal table and must not be introduced as a set of limits.
  const nominal = rows.filter(c => !c.min && !c.max && c.note).length;
  const limits = rows.filter(c => (c.min && c.min !== 'bal') || (c.max && c.max !== 'bal')).length;
  const allNominal = nominal > 0 && limits === 0;
  const someNominal = nominal > 0 && limits > 0;
  //
  // A MIXED TABLE MAY NOT BE CALLED LIMITS EITHER. NIMONIC 901 is the case that
  // forced this: Special Metals heads its table "Nominal Chemical Composition,
  // % (not for specification purposes)" and then prints four bare figures and
  // seven carrying "max". The maxima are real enough to record as maxima, but a
  // caption reading "These are specification limits for the grade" over a table
  // the mill has expressly disclaimed for specification is the site putting
  // words in the mill's mouth. So the three shapes get three captions.
  const heading = allNominal
    ? `Nominal chemical composition for ${esc(fullName(r))}`
    : someNominal
      ? `Chemical composition for ${esc(fullName(r))}`
      : `Chemical composition limits for ${esc(fullName(r))}`;
  const provenance = `${esc(r.source)}, checked ${esc(r.checked)}.`;
  const lead = allNominal
    ? `Nominal composition per ${provenance} The source publishes nominal figures for this grade rather than acceptance limits, and they are not measured values for a lot;`
    : someNominal
      ? `Composition per ${provenance} Figures given as a range or a maximum are limits and those marked <em>nominal</em> are not; none of them are measured values for a lot;`
      : `Composition limits per ${provenance} These are specification limits for the grade, not measured values for a lot;`;
  return [
    '<div class="table-responsive">',
    '<table class="table table-bordered">',
    `<caption class="visually-hidden">${heading}</caption>`,
    '<thead><tr><th scope="col">Element</th><th scope="col">Min (%)</th><th scope="col">Max (%)</th></tr></thead>',
    '<tbody>',
    ...rows.map(c => {
      const nm0 = ELEMENT_NAMES[c.element];
      // A mill that publishes only a NOMINAL composition gives a single figure
      // that is neither a minimum nor a maximum - Special Metals does this for
      // INCOLOY 890, Haynes for several grades. Writing it into a min or max
      // column would assert a limit the mill never stated, so such a row leaves
      // both empty and carries the figure in `note`, printed across both
      // columns and labelled.
      if (!c.min && !c.max && c.note) {
        return `<tr><th scope="row">${nm0 ? `${esc(nm0)} (${esc(c.element)})` : esc(c.element)}</th>` +
          `<td colspan="2"><span class="text-muted">${esc(c.note)}</span></td></tr>`;
      }
      const [lo, hi] = cell(c.min, c.max);
      const nm = ELEMENT_NAMES[c.element];
      // The bulletin's own qualifier, e.g. "if determined" against cobalt in
      // the INCONEL 625 sheet. Printed rather than dropped, so the page can be
      // compared line for line against the mill's table.
      const note = c.note ? ` <span class="small text-muted">(${esc(c.note)})</span>` : '';
      return `<tr><th scope="row">${nm ? `${esc(nm)} (${esc(c.element)})` : esc(c.element)}</th><td>${lo}</td><td>${hi}${note}</td></tr>`;
    }),
    '</tbody>',
    '</table>',
    '</div>',
    `<p class="small text-muted">${lead} the mill test certificate supplied with your order states the actual analysis.</p>`,
  ].join('\n');
}

// ---- page walking -----------------------------------------------------------
const SKIP = new Set(['.git', '.vscode', '.claude', 'node_modules', '_site', 'vendor', 'tools', '.bundle', '.github', 'docs', 'supabase']);
function walk(d, out = []) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const fp = path.join(d, e.name);
    if (e.isDirectory()) walk(fp, out);
    else if (/\.html?$/i.test(e.name)) out.push(fp);
  }
  return out;
}

const norm = s => String(s ?? '').toLowerCase().replace(/\([^)]*\)/g, '').replace(/[^a-z0-9]/g, '');
const familyOf = url => (FAMILY_KEYS.find(([k]) => url.toLowerCase().includes('/' + k + '/')) || [])[1] || null;

// Resolve /family/grade/[form/] to a CSV row. The grade segment is normalised
// so "625-LCF" finds "625 LCF" and "Grade-2" finds "Grade 2".
function gradeForUrl(url) {
  const family = familyOf(url);
  if (!family) return null;
  const segs = url.split('/').filter(Boolean);
  if (segs.length < 2) return null;
  const cand = norm(segs[1]);
  if (!cand) return null;
  const pool = grades.filter(r => r.family === family);
  // Longest grade name first so "625 LCF" wins over "625".
  const sorted = [...pool].sort((a, b) => norm(b.grade).length - norm(a.grade).length);
  return sorted.find(r => norm(r.grade) === cand)
    || sorted.find(r => norm(r.grade).replace(/^(inconel|incoloy|monel|nickel|hastelloy|haynes)/, '') === cand)
    || null;
}

// ---- the lint ---------------------------------------------------------------
// Only the identity zone is checked: title, meta description, og/twitter
// title+description and the JSON-LD name. A UNS in the body is usually a
// legitimate mention of a sibling grade in a cross-link list, and flagging
// those would bury the real findings.
const UNS_RE = /\b([NRSKJWCAGE]\d{5})\b/g;
const WNR_RE = /\b([123]\.\d{4})\b/g;

function identityZone(raw) {
  const head = (raw.match(/<head[\s\S]*?<\/head>/i) || [''])[0];
  const bits = [];
  const t = head.match(/<title>([\s\S]*?)<\/title>/i);
  if (t) bits.push(t[1]);
  for (const m of head.matchAll(/<meta\s+(?:name|property)="(?:description|og:title|og:description|twitter:title|twitter:description)"[^>]*content="([^"]*)"/gi))
    bits.push(m[1]);
  for (const m of raw.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/gi)) {
    for (const n of m[1].matchAll(/"(?:name|description)"\s*:\s*"((?:[^"\\]|\\.)*)"/g)) bits.push(n[1]);
  }
  return bits.join('\n');
}

// How many distinct grades of this family does the zone name? A foil page that
// legitimately covers 660, 686, 690, 693 and 718 must not be judged against
// one of them.
function gradesNamedIn(zone, family) {
  const z = zone.toLowerCase();
  // Where each grade name is mentioned, not merely whether - the spans are what
  // the de-duplication below needs.
  const spans = new Map();
  for (const r of grades.filter(x => x.family === family)) {
    const g = r.grade.replace(/\([^)]*\)/g, '').trim();
    if (!g || g === '-') continue;
    const pat = g.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/[\s-]+/g, '[\\s\\u00ae.-]*');
    const re = new RegExp(`(?:^|[^a-z0-9])(${pat})(?![a-z0-9])`, 'ig');
    const at = [...z.matchAll(re)].map(m => {
      const s = m.index + m[0].length - m[1].length;
      return [s, s + m[1].length];
    });
    if (at.length) spans.set(r.grade, at);
  }
  // "625 LCF" also matches "625", so the shorter name is dropped - but ONLY
  // where every one of its mentions sits inside a longer one. Dropping it
  // unconditionally collapsed /incoloy/800H/, which names both grades and
  // prints a UNS for each ("800H (UNS N08810) and 800HT (N08811)"), down to
  // 800HT alone - so the lint judged N08811 against 800H and reported a page
  // that was right. The mill itself says 800HT "can be certified to either or
  // both UNS numbers", so a page carrying the pair is correct, not a fault.
  for (const [a, aSpans] of [...spans]) {
    for (const [b, bSpans] of spans) {
      if (a === b || !norm(b).startsWith(norm(a))) continue;
      if (aSpans.every(([s, e]) => bSpans.some(([bs, be]) => s >= bs && e <= be))) {
        spans.delete(a);
        break;
      }
    }
  }
  return new Set(spans.keys());
}


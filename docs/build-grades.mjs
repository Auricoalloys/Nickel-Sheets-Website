// Density is kept as a bare number in the CSV precisely so this file can be
// generated. It is written into docs/, which _config.yml excludes from the
// build, so nothing is published until that exclusion is lifted deliberately.
function jsonPayload() {
  return JSON.stringify({
    generated_by: 'docs/build-grades.mjs',
    note: 'Specification data for internal tooling. Density in g/cm3. Only rows verified against a mill bulletin are included.',
    grades: grades.filter(verified).map(r => ({
      family: r.family, grade: r.grade, name: fullName(r),
      uns: unsList(r.uns)[0] || null,
      uns_all: unsList(r.uns),
      wnr: r.wnr && r.wnr !== '-' ? r.wnr : null,
      en_name: r.en_name && r.en_name !== '-' ? r.en_name : null,
      density_g_cm3: r.density_g_cm3 ? Number(r.density_g_cm3) : null,
      melting_c: r.melting_c || null,
      source: r.source, checked: r.checked,
    })),
  }, null, 2) + '\n';
}


#!/usr/bin/env node
/*
 * build-nichrome-facts.mjs - writes a "What is nichrome?" section into
 * nichrome.html from docs/grades.csv, docs/chemistry.csv and docs/properties.csv.
 *
 * WHY. Search Console (2026-10-14) showed /nichrome/ as the site's largest page
 * by impressions (748 in three months, average position 43) and the queries
 * behind them are questions: "nichrome meaning", "nichrome composition",
 * "melting point of nichrome", "nichrome properties", "what is nichrome". The page
 * explained the idea but stated no figure at all - no composition limit, no
 * melting point, no density, no resistivity - so it could not answer any of them.
 *
 * WHY A GENERATOR. The figures already live in three CSVs, each read off a named
 * data sheet (VDM Metals for 80/20, 70/30 and 60/15; JLC Electromet for 40/20,
 * 30/20 and 20/25), and the grade hubs print the same constants. A second hand-
 * typed copy on the family hub is how this site came to state two densities for
 * one alloy (CLAUDE.md, "A generated constant gets one home per page"). Writing
 * the section from the CSVs means it cannot disagree with them, and a grade whose
 * row is not verified publishes nothing here either.
 *
 * It states only what a data sheet printed. A grade with no melting point on its
 * sheet is named as such rather than given a plausible number.
 *
 *   node docs/build-nichrome-facts.mjs          # write the section
 *   node docs/build-nichrome-facts.mjs --check  # report drift, write nothing
 *
 * Works in LF space and restores the CRLF it found; see CLAUDE.md.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");
const PAGE = "nichrome.html";
const FAMILY = "nichrome";
const GRADES = ["80/20", "70/30", "60/15", "40/20", "30/20", "20/25"];

const START = "<!-- nichrome-facts:start  generated by docs/build-nichrome-facts.mjs -->";
const END = "<!-- nichrome-facts:end -->";
const ANCHOR = '<section class="py-4" id="grades">';

/** Rows of a CSV with '#' comment lines: [{column: value}]. */
function readCsv(path) {
  const lines = readFileSync(join(ROOT, path), "utf8").replace(/\r\n/g, "\n").split("\n").filter((l) => l && !l.startsWith("#"));
  const header = lines.shift().split(",");
  return lines.map((l) => {
    const c = l.split(",");
    return Object.fromEntries(header.map((h, i) => [h, (c[i] || "").trim()]));
  });
}

const grades = readCsv("docs/grades.csv").filter((r) => r.family === FAMILY);
const chem = readCsv("docs/chemistry.csv").filter((r) => r.family === FAMILY);
const props = readCsv("docs/properties.csv").filter((r) => r.family === FAMILY);
const hub = Object.fromEntries(readCsv("docs/hub-grades.csv").filter((r) => r.family === FAMILY).map((r) => [r.grade, r]));

// The publication gate every generator here keeps: a verified row only.
const verified = (g) => g && g.checked && g.source && g.source !== "pending";
const rows = GRADES.map((id) => ({ id, g: grades.find((r) => r.grade === id) })).filter((x) => verified(x.g));
if (!rows.length) { console.log("no verified nichrome grade, nothing written"); process.exit(0); }

const esc = (t) => t.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const num = (v) => Number(v).toLocaleString("en-US");
const el = (id, symbol) => chem.find((r) => r.grade === id && r.element === symbol);

/** "19-21%", "at least 57%", "the balance", or '' when the grade lists no such element. */
function amount(id, symbol) {
  const r = el(id, symbol);
  if (!r) return "";
  if (r.max === "bal") return "the balance";
  if (r.min && r.max) return `${r.min.replace(/\.0$/, "")}&ndash;${r.max.replace(/\.0$/, "")}%`;
  if (r.min) return `at least ${r.min.replace(/\.0$/, "")}%`;
  return `at most ${r.max}%`;
}
const label = (id) => `NiCr ${id}`;

/* ---- composition sentence ------------------------------------------------ */
const describe = (id) => {
  const bits = [];
  const ni = amount(id, "Ni"), cr = amount(id, "Cr"), fe = amount(id, "Fe");
  if (cr) bits.push(`chromium ${cr}`);
  if (ni) bits.push(ni === "the balance" ? "nickel the balance" : `${ni.replace("at least ", "at least ")} nickel`);
  if (fe === "the balance") bits.push("iron the balance");
  return `${label(id)} (${bits.join(", ")})`;
};
const nickelBased = rows.filter((x) => { const r = el(x.id, "Ni"); return r && (r.max === "bal" || Number(r.min) >= 50); });
const ironBearing = rows.filter((x) => !nickelBased.includes(x));
const list = (a) => (a.length < 2 ? a.join("") : a.slice(0, -1).join(", ") + " and " + a[a.length - 1]);

let composition =
  `Nichrome is a family of nickel-chromium alloys made for electrical resistance heating, and its grades are named by ` +
  `their nickel-to-chromium ratio. The nickel-based grades are ${list(nickelBased.map((x) => describe(x.id)))}.`;
if (ironBearing.length) {
  composition += ` The iron-bearing grades trade nickel for iron: ${list(ironBearing.map((x) => describe(x.id)))}.`;
}

/* ---- melting point and working temperature ------------------------------ */
const byMelt = new Map();
const noMelt = [];
for (const x of rows) {
  const m = x.g.melting_c;
  if (/^\d+$/.test(m)) { byMelt.set(m, (byMelt.get(m) || []).concat(label(x.id))); } else noMelt.push(label(x.id));
}
const meltParts = [...byMelt].sort((a, b) => b[0] - a[0]).map(([m, gs]) => `${list(gs)} ${gs.length > 1 ? "melt" : "melts"} at about ${num(m)}&nbsp;&deg;C`);
let melting = meltParts.length ? `${meltParts.join(", and ")}, according to the manufacturer's data sheets.` : "";
if (noMelt.length) {
  melting += ` The data sheet for ${list(noMelt)} publishes no melting point, so none is stated here.`;
}
const maxT = [];
for (const x of rows) {
  for (const p of props.filter((q) => q.grade === x.id && /^Maximum operating temperature in air$/i.test(q.property))) {
    const duty = p.condition ? ` ${p.condition.replace(/^as /, "as a ")}` : "";
    const approx = /approximate/i.test(p.note) ? "approximately " : "";
    maxT.push(`${approx}${num(p.value)}&nbsp;&deg;C for ${label(x.id)}${duty}`);
  }
}
if (maxT.length) {
  melting += ` The temperature an element can be run at in air is lower than the melting point: the data sheets give ${list(maxT)}.`;
}

/* ---- table -------------------------------------------------------------- */
const resistivity = (id) => {
  const v = props.filter((q) => q.grade === id && /^Electrical resistivity$/i.test(q.property) && q.unit === "µΩ·cm").map((q) => Number(q.value));
  // Absent rows mean "not entered in properties.csv", not "the sheet omits it", so
  // this is a dash and never the words "not published" (grades.csv carries that
  // claim only where a comment there verifies it, as for the melting points).
  if (!v.length) return "&mdash;";
  const lo = Math.min(...v), hi = Math.max(...v);
  return lo === hi ? String(lo) : `${lo}&ndash;${hi}`;
};
const tr = rows.map((x) => {
  const h = hub[x.id];
  const name = h && h.link ? `<a href="${h.link}">${esc(label(x.id))}</a>` : esc(label(x.id));
  const ni = amount(x.id, "Ni") || "&mdash;";
  const cr = amount(x.id, "Cr") || "&mdash;";
  const mp = /^\d+$/.test(x.g.melting_c) ? `about ${num(x.g.melting_c)}` : "not published";
  return `              <tr><th scope="row">${name}</th><td>${cr}</td><td>${ni}</td><td>${x.g.density_g_cm3}</td><td>${mp}</td><td>${resistivity(x.id)}</td></tr>`;
}).join("\n");
const sources = [...new Set(rows.map((x) => x.g.source))].map(esc).join("; ");

const block =
`      ${START}
      <section class="py-4" id="what-is-nichrome">
        <h2>What Is Nichrome? Composition, Melting Point and Properties</h2>
        <h3>What is nichrome made of?</h3>
        <p>${composition}</p>
        <h3>What is the melting point of nichrome?</h3>
        <p>${melting}</p>
        <h3>Nichrome properties by grade</h3>
        <div class="table-responsive">
          <table class="table table-bordered grade-table">
            <caption class="visually-hidden">Composition, density, melting point and electrical resistivity of the nichrome grades</caption>
            <thead>
              <tr><th scope="col">Grade</th><th scope="col">Chromium</th><th scope="col">Nickel</th><th scope="col">Density (g/cm&sup3;)</th><th scope="col">Melting point (&deg;C)</th><th scope="col">Resistivity at 20&nbsp;&deg;C (&micro;&Omega;&middot;cm)</th></tr>
            </thead>
            <tbody>
${tr}
            </tbody>
          </table>
        </div>
        <p><small>Figures are read from the manufacturers' data sheets: ${sources}. Resistivity differs by standard where a sheet prints two values, so a range is shown, and a dash means this page states no figure for that grade. Confirm the property you are relying on against the mill certificate for the batch supplied.</small></p>
      </section>
      ${END}
`;

let raw = readFileSync(join(ROOT, PAGE), "utf8");
const crlf = raw.includes("\r\n");
const before = raw.replace(/\r\n/g, "\n");
// The block is written followed by one blank line, so remove both or each run adds another.
let s = before.replace(/[ \t]*<!-- nichrome-facts:start[\s\S]*?<!-- nichrome-facts:end -->\n\n?/g, "");
const at = s.indexOf(ANCHOR);
if (at < 0) { console.error(`${PAGE}: no '${ANCHOR}' to anchor on`); process.exit(1); }
const lineStart = s.lastIndexOf("\n", at) + 1;
s = s.slice(0, lineStart) + block + "\n" + s.slice(lineStart);

if (s === before) { console.log("nichrome facts up to date"); process.exit(0); }
if (CHECK) { console.error("nichrome facts are STALE - run: node docs/build-nichrome-facts.mjs"); process.exit(1); }
writeFileSync(join(ROOT, PAGE), crlf ? s.replace(/\n/g, "\r\n") : s);
console.log(`wrote the nichrome facts section (${rows.length} grades)`);

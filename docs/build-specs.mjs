// Writes the grade x specification tables onto the hub pages, from specs.csv.
//
//   node docs/build-specs.mjs           write the tables into the hubs
//   node docs/build-specs.mjs --check   report drift, write nothing, exit 1
//
// Run it after editing docs/specs.csv and commit the result, exactly like
// docs/build-prices.mjs. This script is excluded from the published site in
// _config.yml; the pages it edits are not.
//
// Why this exists: a standard is written for a product form. B443 covers plate,
// sheet and strip, B446 covers rod, bar and wire, B444 covers pipe and tube.
// The same numbers were being copied by hand onto a product page, a form hub
// and a grade hub, and they drifted - /inconel/625/wire/ cited B443, a plate
// spec, in seven places. Generating the hub tables from one row means a hub can
// only ever print the spec for the form it sells.
//
// Two hub shapes:
//
//   Form hubs  - /inconel-wire-supplier.../, /hollow-bars/...  One form, many
//                grades. Rows are grades; the single spec column is that form.
//   Grade hubs - /inconel/625/  One grade, many forms. Rows are forms.
//
// The table is written between HTML marker comments, so re-running replaces
// only the generated block and never touches hand-written copy around it.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CSV = path.join(ROOT, 'docs', 'specs.csv');
const CHECK = process.argv.includes('--check');

const START = '<!-- specs:start  generated by docs/build-specs.mjs - edit docs/specs.csv -->';
const END = '<!-- specs:end -->';

// Which form column a hub directory sells. hex-bar and hollow-bars are bar
// products; coil is a flat product. Getting this map wrong is the whole bug
// this script prevents, so it is stated once, here.
const FORM_OF_DIR = {
  wire: 'wire',
  'hollow-bars': 'bar',
  'hex-bar': 'bar',
  pipes: 'pipe_tube',
  tube: 'pipe_tube',
  coil: 'flat',
  fittings: 'fitting',
};
const FORM_LABEL = {
  flat: 'Plate, sheet and strip',
  bar: 'Rod and bar',
  wire: 'Wire',
  pipe_tube: 'Pipe and tube',
  fitting: 'Fittings',
};
const FORM_ORDER = ['flat', 'bar', 'wire', 'pipe_tube', 'fitting'];

// A hub URL names its family. Longest key first so "nickel-alloy" is not
// swallowed by "nickel", and "haynes-alloy" resolves before "haynes".
const FAMILY_KEYS = [
  ['special-stainless-steel', 'special-stainless-steel'],
  // The grade hubs live at /stainless/<grade>/, and this key was missing while
  // docs/build-grades.mjs had it - so every one of the nine stainless hubs
  // resolved to a grade there, got its identity table, and was silently skipped
  // here. None of them has ever carried a generated specification table. Listed
  // after the long key above so a /special-stainless-steel-.../ form hub still
  // matches that one first, though both resolve to the same family.
  ['stainless', 'special-stainless-steel'],
  ['nickel-alloy', 'nickel-alloy'],
  ['duplex-steel', 'duplex-steel'],
  ['cobalt-alloy', 'cobalt-alloy'],
  ['titanium-alloy', 'titanium'],
  ['haynes-alloy', 'haynes'],
  ['hastelloy', 'hastelloy'],
  ['nichrome', 'nichrome'],
  ['incoloy', 'incoloy'],
  ['inconel', 'inconel'],
  ['nimonic', 'nimonic'],
  ['titanium', 'titanium'],
  ['haynes', 'haynes'],
  ['monel', 'monel'],
];

// ---- read the CSV -----------------------------------------------------------
if (!fs.existsSync(CSV)) { console.error('docs/specs.csv not found'); process.exit(1); }
const rows = [];
for (const raw of fs.readFileSync(CSV, 'utf8').split(/\r?\n/)) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;
  const c = line.split(',').map(x => x.trim());
  if (c[0] === 'family') continue;                       // header
  const [family, grade, uns, flat, bar, wire, pipe_tube, fitting] = c;
  if (!family || !grade) continue;
  rows.push({ family, grade, uns, flat, bar, wire, pipe_tube, fitting });
}
if (!rows.length) { console.error('docs/specs.csv has no rows'); process.exit(1); }

const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
// "-" means the grade is not made in that form; "mill" means the mill publishes
// no standard for it. Neither is an ASTM number and neither may be invented.
const cell = v => (!v || v === '-') ? '&mdash;' : (v === 'mill' ? 'Mill specification' : esc(v));

function formTable(family, form) {
  const list = rows.filter(r => r.family === family && r[form] && r[form] !== '-');
  if (!list.length) return null;
  const label = FORM_LABEL[form];
  return [
    `<h2>Specifications by Grade &ndash; ${esc(label)}</h2>`,
    `<p>A specification is written for a product form. The standards below are the ones that cover ${label.toLowerCase()}; the plate, bar and tube specifications for these grades are different documents and are listed on their own pages.</p>`,
    '<div class="table-responsive">',
    '<table class="table table-bordered grade-table">',
    '<thead><tr><th scope="col">Grade</th><th scope="col">UNS</th>' +
      `<th scope="col">${esc(label)} specification</th></tr></thead>`,
    '<tbody>',
    ...list.map(r => `<tr><td>${esc(r.grade)}</td><td>${cell(r.uns)}</td><td>${cell(r[form])}</td></tr>`),
    '</tbody>',
    '</table>',
    '</div>',
  ].join('\n');
}

// "625" on its own is not what a buyer writes on a purchase order.
const DISPLAY = {
  inconel: 'Inconel', incoloy: 'Incoloy', hastelloy: 'Hastelloy', monel: 'Monel',
  nimonic: 'Nimonic', haynes: 'Haynes', titanium: 'Titanium', nichrome: 'Nichrome',
  'duplex-steel': 'Duplex', 'cobalt-alloy': '', 'nickel-alloy': '',
  'special-stainless-steel': '',
};
const fullName = row => {
  const p = DISPLAY[row.family] ?? '';
  return p && !row.grade.toLowerCase().startsWith(p.toLowerCase()) ? `${p} ${row.grade}` : row.grade;
};

function gradeTable(row) {
  const forms = FORM_ORDER.filter(f => row[f] && row[f] !== '-');
  if (!forms.length) return null;
  return [
    `<h2>Specifications by Product Form</h2>`,
    `<p>${esc(fullName(row))}${row.uns && row.uns !== '-' ? ` (${esc(row.uns)})` : ''} is supplied to a different standard in each form. Quote the one that matches the product you are ordering.</p>`,
    '<div class="table-responsive">',
    '<table class="table table-bordered grade-table">',
    '<thead><tr><th scope="col">Product form</th><th scope="col">Specification</th></tr></thead>',
    '<tbody>',
    ...forms.map(f => `<tr><td>${esc(FORM_LABEL[f])}</td><td>${cell(row[f])}</td></tr>`),
    '</tbody>',
    '</table>',
    '</div>',
  ].join('\n');
}

// ---- find the hubs ----------------------------------------------------------
const SKIP = new Set(['.git', '.vscode', '.claude', 'node_modules', '_site', 'vendor', 'tools', '.bundle', '.github', 'docs']);
function walk(d, out = []) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const fp = path.join(d, e.name);
    if (e.isDirectory()) walk(fp, out);
    else if (/\.html?$/i.test(e.name)) out.push(fp);
  }
  return out;
}
const familyOf = url => (FAMILY_KEYS.find(([k]) => url.includes(k)) || [])[1] || null;

// SINGLE-GRADE FAMILIES: the grade is the first URL segment and there is no
// family segment, so /kovar/ is a grade hub one segment long. The grade-hub
// branch below requires two segments and therefore never saw it. Kept in step
// with the identical map in docs/build-grades.mjs - a grade added to one and
// not the other gets its spec table written with nothing linting the page.
const SINGLE_GRADE = {
  kovar: ['nickel-alloy', 'Kovar'],
};

// GRADE SEGMENT ALIASES, keyed family -> normalised segment -> normalised grade.
// /stainless/SMO-254/ normalises to "smo254" and the CSV grade "254 SMO" to
// "254smo", so the hub matched no row and got no spec table. Kept in step with
// the identical map in docs/build-grades.mjs, which carries the full reasoning.
const GRADE_ALIAS = {
  'special-stainless-steel': { smo254: '254smo' },
};

// ---- apply ------------------------------------------------------------------
let wrote = 0, drift = [], noAnchor = [], noData = [];

for (const fp of walk(ROOT)) {
  const rel = path.relative(ROOT, fp).split(path.sep).join('/');
  const raw = fs.readFileSync(fp, 'utf8');
  const fm = raw.match(/^﻿?---\s*\r?\n([\s\S]*?)\r?\n---/);
  if (!fm || /^published:\s*false/m.test(fm[1])) continue;
  let url = ((fm[1].match(/^permalink:\s*(.+)$/m) || [, ''])[1] || '').trim().replace(/^["']|["']$/g, '');
  if (!url) continue;
  if (!url.endsWith('/')) url += '/';

  const dir = rel.split('/')[0];
  let table = null;

  if (FORM_OF_DIR[dir]) {
    const family = familyOf(url);
    if (family) table = formTable(family, FORM_OF_DIR[dir]);
    if (family && !table) noData.push(`${rel}  (${family} / ${FORM_OF_DIR[dir]})`);
  } else {
    // grade hub: /family/grade/ with no form segment, or /grade/ for a
    // single-grade family, which has no family segment to carry.
    const one = url.match(/^\/([a-zA-Z0-9-]+)\/$/);
    const sg = one && SINGLE_GRADE[one[1].toLowerCase()];
    if (sg) {
      const row = rows.find(r => r.family === sg[0] && r.grade === sg[1]);
      if (row) table = gradeTable(row);
      else noData.push(`${rel}  (${sg[0]} / ${sg[1]} - no specs.csv row)`);
    } else {
      const m = url.match(/^\/([a-zA-Z0-9-]+)\/([a-zA-Z0-9.-]+)\/$/);
      if (!m) continue;
      const family = familyOf('/' + m[1] + '/');
      if (!family) continue;
      const seg = m[2].toLowerCase().replace(/[^a-z0-9]/g, '');
      const g = (GRADE_ALIAS[family] || {})[seg] || seg;
      const row = rows.find(r => r.family === family &&
        r.grade.toLowerCase().replace(/[^a-z0-9]/g, '').replace(/^(inconel|incoloy|monel|nickel|hastelloy)/, '') === g);
      if (row) table = gradeTable(row);
    }
  }
  if (!table) continue;

  const crlf = raw.includes('\r\n');
  let s = raw.replace(/\r\n/g, '\n');
  const before = s;
  const block = `${START}\n${table}\n${END}`;

  if (s.includes(START)) {
    s = s.replace(new RegExp(START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[\\s\\S]*?' + END), block);
  } else {
    // Append inside the Specifications section where there is one, otherwise
    // open the Equivalent Grades section with it. A hub with neither is
    // reported rather than guessed at - same rule as build-prices.mjs.
    const spec = s.indexOf('<section class="spec-table-section" id="specification">');
    const eq = s.indexOf('<section class="grade-table-section" id="equivalent-grades">');
    // The grade hubs use a plainer template with no sections at all: an
    // "Available Forms" list and little else. The table belongs directly under
    // that list, which is where a reader has just picked their form.
    const forms = (m => m ? m.index : -1)(s.match(/<h[23]>Available Forms:?<\/h[23]>/));
    if (spec > -1) {
      const end = s.indexOf('</section>', spec);
      if (end < 0) { noAnchor.push(rel); continue; }
      s = s.slice(0, end) + block + '\n' + s.slice(end);
    } else if (eq > -1) {
      const open = s.indexOf('>', eq) + 1;
      s = s.slice(0, open) + '\n' + block + s.slice(open);
    } else if (forms > -1) {
      const end = s.indexOf('</ul>', forms);
      if (end < 0) { noAnchor.push(rel); continue; }
      s = s.slice(0, end + 5) + '\n\n' + block + s.slice(end + 5);
    } else {
      noAnchor.push(rel);
      continue;
    }
  }

  if (s !== before) {
    if (CHECK) drift.push(rel);
    else { fs.writeFileSync(fp, crlf ? s.replace(/\n/g, '\r\n') : s); wrote++; }
  }
}

if (CHECK) {
  if (drift.length) {
    console.error(`spec tables are STALE in ${drift.length} hub(s) - run: node docs/build-specs.mjs`);
    drift.slice(0, 10).forEach(d => console.error('   ' + d));
    process.exit(1);
  }
  console.log(`spec tables are current (${rows.length} grades in docs/specs.csv)`);
  process.exit(0);
}

console.log(`spec tables written from docs/specs.csv`);
console.log(`  grades in the CSV     : ${rows.length}`);
console.log(`  hubs updated          : ${wrote}`);
if (noData.length) {
  console.log(`  no grades for that family and form (${noData.length}) - no table written:`);
  noData.forEach(x => console.log('     ' + x));
}
if (noAnchor.length) {
  console.log(`  nowhere on the page to put the table (${noAnchor.length}) - skipped:`);
  noAnchor.forEach(x => console.log('     ' + x));
}

// weight-calculator.js - the metal weight calculator at /tools/weight-calculator/.
//
// What it computes is a THEORETICAL weight: nominal density multiplied by the
// volume of an ideal shape. That is honest arithmetic and the page says so in
// as many words. It is not a shipping weight and it is not a supply
// commitment - rolling tolerance alone moves a thin sheet by a few percent, and
// CLAUDE.md's rule about commercial figures applies here exactly as it does to
// prices: what the business will actually ship is the business's to state.
//
// Densities come from javascript/weight-data.js, generated by
// docs/build-weight-data.mjs. Every mill-tier figure carries the bulletin it
// was read from and the page prints it, because a calculator that will not say
// where its number came from is asking to be trusted rather than checked.

import { MATERIALS, GROUP_ORDER } from "./weight-data.js";

/* ------------------------------------------------------------------ *
 * Units
 * ------------------------------------------------------------------ */

// Everything is converted to millimetres, volume is computed in mm3, and the
// single conversion to mass happens once at the end. Mixing unit systems part
// way through a formula is how a calculator ends up off by 25.4.
const TO_MM = { mm: 1, cm: 10, m: 1000, in: 25.4, ft: 304.8 };

const LB_PER_KG = 2.2046226218;


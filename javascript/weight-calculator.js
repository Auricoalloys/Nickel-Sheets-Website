// ?material=inconel-625&shape=round-bar. Shareable, and the hook the per-page
// widget will use when the calculator is embedded on the form pages.
function applyQueryString() {
  const q = new URLSearchParams(window.location.search);
  const material = q.get("material");
  if (material && (material === CUSTOM || MATERIAL_BY_ID.has(material))) {
    $("wc-material").value = material;
    customByChoice = material === CUSTOM;
  }
  const shape = q.get("shape");
  if (shape && SHAPE_BY_KEY.has(shape)) $("wc-shape").value = shape;
  const unit = q.get("unit");
  if (unit && TO_MM[unit]) $("wc-unit").value = unit;
}

function init() {
  if (!$("wc-form")) return;

  buildFamilyFilter($("wc-family"));
  buildMaterialSelect();
  buildShapeSelect($("wc-shape"));

  // A sensible starting point rather than a blank form.
  $("wc-material").value = MATERIAL_BY_ID.has("inconel-625")
    ? "inconel-625"
    : MATERIALS[0].id;
  $("wc-shape").value = "sheet";

  applyQueryString();
  applyMaterial();
  buildFields();

  // Narrowing the list only reapplies the material when the selection actually
  // moved - otherwise typing in the search box would wipe a density override
  // the visitor had just entered.
  const refilter = () => {
    if (buildMaterialSelect()) applyMaterial();
    calculate();
  };
  $("wc-family").addEventListener("change", refilter);
  $("wc-search").addEventListener("input", refilter);

  $("wc-material").addEventListener("change", () => {
    customByChoice = $("wc-material").value === CUSTOM;
    applyMaterial();
    calculate();
  });
  $("wc-shape").addEventListener("change", () => {
    buildFields();
    calculate();
  });

  for (const id of [
    "wc-custom-name",
    "wc-quantity",
    "wc-rate",
    "wc-unit",
    "wc-currency",
  ]) {
    $(id).addEventListener("input", calculate);
    $(id).addEventListener("change", calculate);
  }

  $("wc-density").addEventListener("input", calculate);

  $("wc-form").addEventListener("submit", (e) => e.preventDefault());

  $("wc-quote").addEventListener("click", (e) => {
    e.preventDefault();
    track(EVENTS.calculatorQuote, {
      page_path: window.location.pathname,
      material: lastResult?.materialName,
      shape: lastResult?.shapeLabel,
      method: "form",
    });
    // Open the site-wide enquiry form in place, pre-filled - no page reload, the
    // visitor stays with the number they just calculated. Fall back to the
    // contact page carrying the same ?enquiry= seed if the form module has not
    // loaded for any reason.
    const line = quoteLine();
    if (line && typeof window.floatingForm?.openWith === "function") {
      window.floatingForm.openWith(line);
    } else {
      window.location.href = quoteHref();
    }
  });

  // The WhatsApp button is a real <a> that opens the chat itself; this only
  // records that the result turned into an enquiry, under the same event as the
  // form path so the funnel reads as one number split by method. (The generic
  // contact_click also fires, from floating-form's rail tracking - that is fine,
  // a different event for a different question.)
  $("wc-whatsapp").addEventListener("click", () => {
    track(EVENTS.calculatorQuote, {
      page_path: window.location.pathname,
      material: lastResult?.materialName,
      shape: lastResult?.shapeLabel,
      method: "whatsapp",
    });
  });

  calculate();
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", init);
} else {
  init();
}

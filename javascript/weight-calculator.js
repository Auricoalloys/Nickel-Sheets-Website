// Each shape declares its inputs and the volume of ONE piece in mm3.
//
//   per: "linear"  sold by length  -> the derived figure is kg per metre
//   per: "flat"    sold by area    -> kg per square metre, from `thickness`
//
// `extras` adds rows that only make sense for that shape - the developed strip
// length of a coil, for instance.
//
// Rolled structural sections (angle, tee, channel, beam) are computed from
// their plate geometry and IGNORE the root and toe radii, so they come out
// light against a mill section table. Measured against IS 808:
//
//   ISA 50x50x6   4.427 vs 4.50 kg/m   -1.6%
//   ISMB 200     24.939 vs 25.4 kg/m   -1.8%
//   ISMC 100      9.024 vs 9.56 kg/m   -5.6%
//
// The channel is the bad one: IS channels carry a large root radius (R1 = 9 mm
// on an ISMC 100) and a tapered flange, and neither is in this formula. -5.6%
// on a structural order is a real error, not a rounding difference, so the page
// states the measured deviations and tells the reader to use the mill's section
// table for a standard designation. Do not soften that to "approximate".


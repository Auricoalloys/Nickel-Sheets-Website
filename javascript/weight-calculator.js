const $ = (id) => document.getElementById(id);

const CUSTOM = "custom";
const MATERIAL_BY_ID = new Map(MATERIALS.map((m) => [m.id, m]));

function buildMaterialSelect(select) {
  const custom = document.createElement("option");
  custom.value = CUSTOM;
  custom.textContent = "— Custom material (enter your own density) —";
  select.append(custom);

  const groups = new Map();
  for (const m of MATERIALS) {
    if (!groups.has(m.group)) groups.set(m.group, []);
    groups.get(m.group).push(m);
  }

  for (const name of GROUP_ORDER) {
    const rows = groups.get(name);
    if (!rows || !rows.length) continue;
    const og = document.createElement("optgroup");
    og.label = name;
    for (const m of rows) {
      const opt = document.createElement("option");
      opt.value = m.id;
      // A grade with no published density still appears, flagged, rather than
      // going silently missing from a list that shows its siblings.
      opt.textContent = m.density
        ? `${m.name} — ${m.density} g/cm³`
        : `${m.name} — density not published`;
      og.append(opt);
    }
    select.append(og);
  }
}

function buildShapeSelect(select) {
  for (const groupName of SHAPE_GROUPS) {
    const og = document.createElement("optgroup");
    og.label = groupName;
    for (const s of SHAPES.filter((x) => x.group === groupName)) {
      const opt = document.createElement("option");
      opt.value = s.key;
      opt.textContent = s.label;
      og.append(opt);
    }
    select.append(og);
  }
}

function applyMaterial() {
  const id = $("wc-material").value;
  const density = $("wc-density");
  const provenance = $("wc-provenance");

  $("wc-reset-density").hidden = true;

  if (id === CUSTOM) {
    $("wc-custom-name-row").hidden = false;
    density.value = "";
    density.placeholder = "e.g. 7.85";
    provenance.innerHTML =
      "<strong>Your own figure.</strong> Enter the density from your material " +
      "certificate or the mill's data sheet.";
    provenance.className = "wc-provenance wc-provenance-custom";
    return;
  }

  $("wc-custom-name-row").hidden = true;
  const m = MATERIAL_BY_ID.get(id);
  if (!m) return;

  density.value = m.density ?? "";
  density.placeholder = m.density ? "" : "enter density";

  if (!m.density) {
    provenance.innerHTML =
      "<strong>No density published.</strong> " +
      escapeHtml(m.source || "The source for this grade") +
      " does not give one, so we will not invent it. Enter the figure from " +
      "your material certificate.";
    provenance.className = "wc-provenance wc-provenance-missing";
  } else if (m.tier === "mill") {
    provenance.innerHTML =
      "<strong>Mill-sourced.</strong> " +
      escapeHtml(String(m.density)) +
      " g/cm³, read from " +
      escapeHtml(m.source) +
      (m.note ? ` (${escapeHtml(m.note)})` : "") +
      ".";
    provenance.className = "wc-provenance wc-provenance-mill";
  } else {
    provenance.innerHTML =
      "<strong>Nominal figure.</strong> " +
      (m.source === "CRC Handbook"
        ? "Element density from the CRC Handbook."
        : "A representative handbook value — real tempers and heats vary by " +
          "around 1%.") +
      (m.note ? ` ${escapeHtml(m.note)}.` : "");
    provenance.className = "wc-provenance wc-provenance-nominal";
  }
}

function buildFields() {
  const shape = SHAPE_BY_KEY.get($("wc-shape").value);
  const host = $("wc-dimensions");
  // Carrying values across a shape change means switching from Round Bar to
  // Wire keeps the diameter and length already typed.
  const previous = new Map(
    [...host.querySelectorAll("input")].map((i) => [i.dataset.k, i.value])
  );
  host.textContent = "";

  for (const f of shape.fields) {
    const wrap = document.createElement("div");
    wrap.className = "wc-field";

    const label = document.createElement("label");
    label.setAttribute("for", `wc-dim-${f.k}`);
    label.textContent = f.label;

    const input = document.createElement("input");
    input.type = "number";
    input.id = `wc-dim-${f.k}`;
    input.dataset.k = f.k;
    input.min = "0";
    input.step = "any";
    input.inputMode = "decimal";
    input.autocomplete = "off";
    if (previous.has(f.k)) input.value = previous.get(f.k);

    wrap.append(label, input);
    host.append(wrap);
  }

  host.querySelectorAll("input").forEach((i) =>
    i.addEventListener("input", calculate)
  );

  $("wc-rolled-note").hidden = !shape.rolled;
}

function readDimensions(shape) {
  const unit = $("wc-unit").value;
  const factor = TO_MM[unit];
  const raw = {};
  const mm = {};
  let missing = false;

  for (const f of shape.fields) {
    const v = parseFloat($(`wc-dim-${f.k}`).value);
    if (!Number.isFinite(v) || v <= 0) {
      missing = true;
      raw[f.k] = null;
      mm[f.k] = null;
    } else {
      raw[f.k] = v;
      mm[f.k] = v * factor;
    }
  }
  return { raw, mm, missing, unit };
}

let lastResult = null;

function calculate() {
  const shape = SHAPE_BY_KEY.get($("wc-shape").value);
  const results = $("wc-results");
  const density = parseFloat($("wc-density").value);
  const qty = Math.max(1, parseInt($("wc-quantity").value, 10) || 1);
  const { raw, mm, missing, unit } = readDimensions(shape);

  const fail = (msg) => {
    lastResult = null;
    $("wc-quote").hidden = true;
    results.className = "wc-results wc-results-empty";
    results.innerHTML = `<p class="wc-placeholder">${escapeHtml(msg)}</p>`;
  };

  if (!Number.isFinite(density) || density <= 0) {
    return fail("Enter a density to calculate a weight.");
  }
  if (missing) return fail("Fill in every dimension to see the weight.");

  const invalid = shape.check ? shape.check(mm) : null;
  if (invalid) return fail(invalid);

  const volumeMm3 = shape.volume(mm);
  if (!(volumeMm3 > 0)) {
    return fail("Those dimensions leave no material — check the wall or bore.");
  }

  // mm3 -> cm3 is /1000; g -> kg is /1000. One conversion, done once.
  const kgEach = (volumeMm3 * density) / 1e6;
  const kgTotal = kgEach * qty;

  // The per-metre / per-square-metre figure a stockist's customer quotes
  // against. kg/m2 reduces to thickness_mm * density: one square metre of t mm
  // plate is t/1000 m3, and a density in g/cm3 is 1000x the same number in
  // kg/m3, so the two thousands cancel.
  const rows = [];
  if (shape.per === "linear" && shape.run) {
    rows.push({
      label: "Unit weight",
      value: `${fmt(kgEach / (shape.run(mm) / 1000))} kg per metre`,
    });
  } else if (shape.per === "flat" && Number.isFinite(mm.thickness)) {
    rows.push({
      label: "Unit weight",
      value: `${fmt(mm.thickness * density)} kg per m²`,
    });
  }
  if (shape.extras) rows.push(...shape.extras(mm, density));

  const rate = parseFloat($("wc-rate").value);
  const currency = $("wc-currency").value;
  const hasRate = Number.isFinite(rate) && rate > 0;

  const materialName =
    $("wc-material").value === CUSTOM
      ? $("wc-custom-name").value.trim() || "Custom material"
      : MATERIAL_BY_ID.get($("wc-material").value)?.name || "Material";

  const dims = shape.describe(raw, unit);

  lastResult = {
    materialName,
    shapeLabel: shape.label,
    dims,
    qty,
    kgTotal,
  };

  results.className = "wc-results";
  results.innerHTML = `
    <div class="wc-headline">
      <span class="wc-headline-value">${fmt(kgTotal)}</span>
      <span class="wc-headline-unit">kg</span>
      <span class="wc-headline-sub">${
        qty > 1 ? `total for ${qty} pieces` : "total"
      }</span>
    </div>
    <dl class="wc-breakdown">
      <div><dt>Weight per piece</dt><dd>${fmt(kgEach)} kg</dd></div>
      <div><dt>Total in pounds</dt><dd>${fmt(kgTotal * LB_PER_KG)} lb</dd></div>
      ${rows
        .map(
          (r) =>
            `<div><dt>${escapeHtml(r.label)}</dt><dd>${escapeHtml(
              r.value
            )}</dd></div>`
        )
        .join("")}
      <div><dt>Density used</dt><dd>${escapeHtml(
        String(density)
      )} g/cm³</dd></div>
      ${
        hasRate
          ? `<div class="wc-cost"><dt>At ${fmtMoney(
              rate,
              currency
            )}/kg</dt><dd>${fmtMoney(kgTotal * rate, currency)}</dd></div>`
          : ""
      }
    </dl>
    <p class="wc-theoretical">
      Theoretical weight for ${escapeHtml(materialName)} —
      ${/* Not .toLowerCase(): it turns "Pipe / Round Tube (OD × wall)" into
           "(od × wall)" and the coil label into "coil (by coil od and id)". */ ""}
      ${escapeHtml(shape.label)}, ${escapeHtml(dims)}.
      Actual weight varies with rolling and wall tolerance${
        shape.rolled ? ", and this figure excludes root radii" : ""
      }.
    </p>`;

  $("wc-quote").hidden = false;
}

// Hands the enquiry form a subject that says what was actually calculated. An
// explicit ?enquiry= always beats the breadcrumb-derived seed, which is why
// this route exists rather than relying on the page's own crumb - "Weight
// Calculator" would tell the sales desk nothing.
function quoteHref() {
  if (!lastResult) return "/pages/contact/";
  const r = lastResult;
  const line =
    `${r.materialName} — ${r.shapeLabel} — ${r.dims} — ` +
    `${r.qty} pc${r.qty > 1 ? "s" : ""} — ${fmt(r.kgTotal)} kg theoretical`;
  return `/pages/contact/?enquiry=${encodeURIComponent(line.slice(0, 280))}`;
}


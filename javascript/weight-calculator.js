// A calculator that prints 0.00 kg for a foil blank looks broken, and one that
// prints 12847.3892456 kg looks unserious. Scale the precision to the
// magnitude instead of picking one and living with both failures.
function fmt(n) {
  if (!Number.isFinite(n)) return "—";
  const abs = Math.abs(n);
  let dp;
  if (abs === 0) dp = 0;
  else if (abs < 0.001) dp = 6;
  else if (abs < 0.1) dp = 4;
  else if (abs < 10) dp = 3;
  else if (abs < 1000) dp = 2;
  else dp = 1;
  return n.toLocaleString("en-IN", {
    minimumFractionDigits: dp,
    maximumFractionDigits: dp,
  });
}

function fmtMoney(n, currency) {
  if (!Number.isFinite(n)) return "—";
  return (
    (currency === "USD" ? "$" : "₹") +
    n.toLocaleString(currency === "USD" ? "en-US" : "en-IN", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })
  );
}

function escapeHtml(s) {
  return String(s).replace(
    /[&<>"']/g,
    (c) =>
      ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#39;",
      })[c]
  );
}

